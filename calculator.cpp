#ifdef _WIN32 // Проверяет, компилируется ли программа для операционной системы Windows.
#include <windows.h> // Подключает функции Windows для настройки кодировки консоли.
#endif // Завершает условное подключение функций Windows.
#include <iostream> // Подключает средства стандартного ввода и вывода.
#include <limits> // Подключает числовые пределы для безопасной очистки потока ввода.
double readNumber(const char* prompt) { // Объявляет функцию безопасного чтения числа с подсказкой.
    double number = 0.0; // Создаёт переменную для введённого пользователем числа.
    while (true) { // Повторяет запрос, пока пользователь не введёт корректное число.
        std::cout << prompt; // Выводит переданную функции подсказку.
        if (std::cin >> number) { // Проверяет, удалось ли преобразовать введённое значение в число.
            return number; // Возвращает корректно введённое число из функции.
        } // Завершает проверку успешного чтения числа.
        std::cout << "Ошибка: введите корректное число.\n"; // Сообщает пользователю об ошибке ввода.
        std::cin.clear(); // Сбрасывает состояние ошибки стандартного потока ввода.
        std::cin.ignore(std::numeric_limits<std::streamsize>::max(), '\n'); // Удаляет ошибочные данные до конца строки.
    } // Завершает цикл повторного запроса числа.
} // Завершает функцию безопасного чтения числа.
int main() { // Объявляет главную функцию программы.
#ifdef _WIN32 // Проверяет, запущена ли программа в Windows.
    SetConsoleCP(CP_UTF8); // Устанавливает кодировку UTF-8 для ввода в консоли Windows.
    SetConsoleOutputCP(CP_UTF8); // Устанавливает кодировку UTF-8 для вывода в консоли Windows.
#endif // Завершает настройку кодировки для Windows.
    char repeat = 'y'; // Создаёт переменную для ответа о продолжении вычислений.
    std::cout << "Калькулятор запущен.\n"; // Сообщает пользователю о запуске программы.
    while (repeat == 'y' || repeat == 'Y') { // Повторяет вычисления, пока пользователь выбирает продолжение.
        const double firstNumber = readNumber("Введите первое число: "); // Запрашивает и сохраняет первое число.
        char operation = '\0'; // Создаёт переменную для выбранной математической операции.
        std::cout << "Введите операцию (+, -, *, /): "; // Просит пользователя выбрать математическую операцию.
        std::cin >> operation; // Считывает выбранную пользователем операцию.
        if (operation != '+' && operation != '-' && operation != '*' && operation != '/') { // Проверяет, поддерживается ли выбранная операция.
            std::cout << "Ошибка: неизвестная операция.\n"; // Сообщает пользователю о неподдерживаемой операции.
            continue; // Возвращает выполнение к началу цикла вычислений.
        } // Завершает проверку выбранной операции.
        const double secondNumber = readNumber("Введите второе число: "); // Запрашивает и сохраняет второе число.
        double result = 0.0; // Создаёт переменную для результата вычисления.
        bool hasResult = true; // Создаёт признак успешного получения результата.
        switch (operation) { // Выбирает вычисление в зависимости от указанной операции.
            case '+': // Начинает обработку операции сложения.
                result = firstNumber + secondNumber; // Складывает первое и второе числа.
                break; // Завершает обработку операции сложения.
            case '-': // Начинает обработку операции вычитания.
                result = firstNumber - secondNumber; // Вычитает второе число из первого.
                break; // Завершает обработку операции вычитания.
            case '*': // Начинает обработку операции умножения.
                result = firstNumber * secondNumber; // Умножает первое число на второе.
                break; // Завершает обработку операции умножения.
            case '/': // Начинает обработку операции деления.
                if (secondNumber == 0.0) { // Проверяет, не пытается ли пользователь делить на ноль.
                    std::cout << "Ошибка: делить на ноль нельзя.\n"; // Сообщает о невозможности деления на ноль.
                    hasResult = false; // Отмечает, что результат вычисления отсутствует.
                } else { // Выполняет следующий блок, если делитель не равен нулю.
                    result = firstNumber / secondNumber; // Делит первое число на второе.
                } // Завершает проверку деления на ноль.
                break; // Завершает обработку операции деления.
            default: // Добавляет защитную ветвь для непредвиденной операции.
                hasResult = false; // Отмечает отсутствие результата для непредвиденной операции.
                break; // Завершает обработку защитной ветви.
        } // Завершает выбор математической операции.
        if (hasResult) { // Проверяет, было ли вычисление выполнено успешно.
            std::cout << "Результат: " << result << '\n'; // Выводит полученный результат вычисления.
        } // Завершает проверку наличия результата.
        std::cout << "Продолжить вычисления? (y/n): "; // Спрашивает пользователя о необходимости нового вычисления.
        std::cin >> repeat; // Считывает ответ пользователя о продолжении работы.
    } // Завершает цикл повторяющихся вычислений.
    std::cout << "Калькулятор закрыт.\n"; // Сообщает пользователю о завершении программы.
    return 0; // Завершает программу с кодом успешного выполнения.
} // Завершает главную функцию программы.

